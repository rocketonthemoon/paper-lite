// Regenerates shared/css-properties.js: every style property Chrome knows, in camelCase. The MCP lint uses the list
// to tell agents about style keys that have no effect ("colour"). Run it after upgrading Chrome:
//   node scripts/gen-css-properties.mjs            (or CHROME_PATH=/path/to/chrome node scripts/…)
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "shared/css-properties.js");
const CANDIDATES = [
  process.env.CHROME_PATH,
  "C:/Program Files/Google/Chrome/Application/chrome.exe",
  "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
  "/usr/local/bin/chrome-headless-shell", "/usr/bin/chromium-headless-shell",
  "/usr/bin/google-chrome", "/usr/bin/google-chrome-stable", "/usr/bin/chromium", "/usr/bin/chromium-browser",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
].filter((p) => p && fs.existsSync(p));

// Runs in the page: collect the camelCase property names a CSSStyleDeclaration exposes, and print them as JSON.
const PAGE = `<script>
const st = document.createElement("div").style, set = new Set();
for (let o = st; o; o = Object.getPrototypeOf(o)) for (const k of Object.getOwnPropertyNames(o)) set.add(k);
const cs = getComputedStyle(document.documentElement);
for (let i = 0; i < cs.length; i++) set.add(cs[i].replace(/-([a-z])/g, (_, c) => c.toUpperCase()));
const names = [...set].filter((k) => /^[a-zA-Z][a-zA-Z0-9]*$/.test(k) && typeof st[k] === "string"
  && !/^(cssText|cssFloat|length|parentRule)$/.test(k)).sort();
document.documentElement.innerHTML = "<pre id=out></pre>";
document.getElementById("out").textContent = JSON.stringify(names);
</script>`;

let names = null;
for (const exe of CANDIDATES) {
  try {
    const html = execFileSync(exe, ["--headless", "--no-sandbox", "--disable-gpu", "--dump-dom", `data:text/html,${encodeURIComponent(PAGE)}`], {
      encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], timeout: 30_000,
    });
    const m = /<pre id="out">([\s\S]*?)<\/pre>/.exec(html);
    if (m) { names = JSON.parse(m[1].replace(/&quot;/g, '"').replace(/&amp;/g, "&")); console.log(`Read ${names.length} properties from ${exe}`); break; }
  } catch {}
}
if (!names?.length) {
  console.error(`No Chrome/Chromium could be run (tried: ${CANDIDATES.join(", ") || "none found"}). Set CHROME_PATH.`);
  process.exit(1);
}

const lines = [];
let cur = "  ";
for (const n of names) {
  const t = `${JSON.stringify(n)}, `;
  if ((cur + t).length > 118) { lines.push(cur.trimEnd()); cur = "  "; }
  cur += t;
}
lines.push(cur.trimEnd());
fs.writeFileSync(OUT, `// Every style property Chromium knows, in camelCase (generated by scripts/gen-css-properties.mjs). Used to warn
// agents about style keys that have no effect, such as "colour" or "textColour". Regenerate after upgrading Chrome.
export const CSS_PROPERTIES = new Set([
${lines.join("\n")}
]);
`);
console.log(`Wrote ${path.relative(ROOT, OUT)}`);
